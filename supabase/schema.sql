create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  xp integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.saved_combos (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  tricks text[] not null,
  style text not null,
  difficulty text,
  created_at timestamptz not null default now()
);

create table if not exists public.challenge_completions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_title text not null,
  xp_earned integer not null default 0,
  completed_at timestamptz not null default now(),
  unique(user_id, challenge_title)
);

alter table public.profiles enable row level security;
alter table public.saved_combos enable row level security;
alter table public.challenge_completions enable row level security;

create policy "Profiles are readable by everyone" on public.profiles for select using (true);
create policy "Users can insert own profile" on public.profiles for insert with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles for update using (auth.uid() = id);
create policy "Users manage own saved combos" on public.saved_combos for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own challenge completions" on public.challenge_completions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Automatically create a rider profile on sign-up.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, username)
  values (new.id, coalesce(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)));
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();
